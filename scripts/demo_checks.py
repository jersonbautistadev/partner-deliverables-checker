"""An executable engine demonstration that does not require Django."""
import io
import html
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from PIL import Image  # noqa: E402

from checker.engine import ENGINE_VERSION, evaluate, fingerprint, inspect_upload  # noqa: E402


def main():
    rules = [
        {"id": 1, "revision": 1, "title": "Article: 10–20 words", "kind": "word_count", "slot": "article", "config": {"min": 10, "max": 20}},
        {"id": 2, "revision": 1, "title": "Mention event name", "kind": "required_phrase", "slot": "article", "config": {"phrase": "CS Expo 2026"}},
        {"id": 3, "revision": 1, "title": "Square image", "kind": "dimensions", "slot": "image", "config": {"width": 1080, "height": 1080}},
        {"id": 4, "revision": 1, "title": "Caption file", "kind": "required_file", "slot": "caption", "config": {}},
        {"id": 5, "revision": 1, "title": "Logo placement", "kind": "manual", "slot": "image", "config": {}},
    ]
    for r in rules:
        r.update(approved=True, ambiguous=False, source="FICTIONAL · Demo brief")
    image = io.BytesIO()
    Image.new("RGB", (1000, 1000), "#d9ebe2").save(image, "PNG")
    assets = {
        "article": inspect_upload("press.txt", b"CS Expo 2026 brings student projects together for practical demonstrations and thoughtful discussions.", "article"),
        "image": inspect_upload("poster.png", image.getvalue(), "image"),
    }
    report = {"fictional_demo": True, "engine_version": ENGINE_VERSION,
              "fingerprint": fingerprint(rules, assets),
              "findings": [{"requirement_id": r["id"], "title": r["title"],
                            "source": r["source"], **evaluate(r, assets.get(r["slot"]))} for r in rules]}
    if len(sys.argv) == 3 and sys.argv[1] == "--html":
        render_html(report, Path(sys.argv[2]))
    else:
        print(json.dumps(report, indent=2, ensure_ascii=False))


def render_html(report, destination):
    findings = report["findings"]
    statuses = {"passed": "Passed", "failed": "Failed", "missing": "Missing", "needs_review": "Needs review"}
    cards = "".join(f'<section class="stat"><span>{label}</span><strong>{sum(f["status"] == status for f in findings):02d}</strong><small>Items in this fictional example</small></section>' for status, label in statuses.items())
    rows = "".join(f'<article class="finding"><div class="finding-heading"><h3>{html.escape(f["title"])}</h3><span class="badge {f["status"]}">{statuses[f["status"]]}</span></div><p>{html.escape(f["message"])}</p><small>Requirement #{f["requirement_id"]} · v1</small><p class="source">{html.escape(f["source"])}</p></article>' for f in findings)
    css = (Path(__file__).resolve().parents[1] / "static" / "app.css").read_text()
    body = f'''<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Partner Deliverables · Engine demo</title><style>{css}</style></head><body><div class="topbar"><strong>✓ Partner Deliverables Checker</strong><span>Verified checking-engine output · Fictional data</span></div><main style="max-width:1120px"><div class="page-heading"><div><p class="eyebrow">WORKING INCREMENT 01 · CHECKING ENGINE</p><h1>Every finding has a reason.</h1><p class="lede">A real report generated by the Python engine from fictional article and image files.</p></div><span class="badge neutral">Engine {report['engine_version']}</span></div><div class="stats">{cards}</div><section class="panel"><div class="section-heading"><div><h2>Launch press kit · Campus Current</h2><p class="muted">Pre-event publishing instructions · Fictional example</p></div><span class="badge needs_review">Action needed</span></div>{rows}</section><section class="tip"><h3>What this demo verifies</h3><p>The report above comes from executed deterministic checks. This is a standalone engine demo; login, team permissions, uploads through the website, and the dashboard require the Django application. Their runtime verification is still pending in this environment.</p></section><details style="margin-top:22px"><summary>View report JSON</summary><pre>{html.escape(json.dumps(report, indent=2, ensure_ascii=False))}</pre></details><footer>Partner Deliverables Checker<span>Fictional example · No pilot measurements claimed</span></footer></main></body></html>'''
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(body, encoding="utf-8")
    print(f"Wrote engine demonstration to {destination}")


if __name__ == "__main__":
    main()
